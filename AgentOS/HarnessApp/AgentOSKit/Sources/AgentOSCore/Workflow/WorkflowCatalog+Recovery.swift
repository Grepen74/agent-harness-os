extension WorkflowCatalog {
    static var recoveryWorkflow: WorkflowDefinition {
        WorkflowDefinition(kind: .recovery, entryStage: .resumeWork, stages: [
            .init(id: .resumeWork, title: "Resume the node's workflow", actor: .harness),
            .init(id: .escalated, title: "Escalated: a person must act", actor: .person, flags: [.escalated]),
            .init(id: .diagnosis, title: "Diagnose and post advice only", actor: .agent(.diagnoser),
                  flags: [.escalated]),
            .init(id: .infrastructureWait, title: "Wait before the next infrastructure retry", actor: .harness,
                  flags: [.escalated], retrySchedule: .infrastructureRetryDelays),
            .init(id: .questions, title: "Waiting for input", actor: .person, flags: [.needsInput]),
            .init(id: .acceptanceTests, title: "Rewrite acceptance tests", actor: .agent(.testAuthor),
                  phases: [.specified], limits: [.maxAttempts, .maxAgentRuns]),
            .init(id: .breakdownGate, title: "Approve a fresh breakdown", actor: .person,
                  phases: [.specified], gate: .breakdown),
        ], transitions: [
            .init(.resumeWork, .escalated, "A safety limit or failure requires a person",
                  when: [.fact(.escalationRequired)]),
            .init(.escalated, .diagnosis, "An idle escalated node has a diagnoser available",
                  when: [.flagSet(.escalated), .fact(.diagnoserAvailable), .fact(.nodeIdle)]),
            .init(.diagnosis, .escalated, "Post advice without resuming or clearing escalation",
                  when: [.fact(.diagnosisFinished)], effects: [.postDiagnosisAdvice, .preserveEscalation]),
            .init(.escalated, .infrastructureWait, "An eligible infrastructure problem has another retry",
                  when: [.flagSet(.escalated), .fact(.infrastructureProblem), .fact(.retryAvailable)]),
            .init(.infrastructureWait, .resumeWork, "The next configured wait elapsed and the node is idle",
                  when: [.fact(.retryWaitElapsed), .fact(.retryAvailable), .fact(.nodeIdle)]),
            .init(.escalated, .resumeWork, "A person clears escalation and resets attempts",
                  when: [.signal(.retry), .flagSet(.escalated), .fact(.nodeIdle)],
                  actor: .person, effects: [.resetAttempts]),
            .init(.questions, .resumeWork, "A person supplies the required input and retries",
                  when: [.signal(.retry), .flagSet(.needsInput), .fact(.inputResolved), .fact(.nodeIdle)],
                  actor: .person),
            .init(.escalated, .acceptanceTests, "A person discards an unlanded leaf's tests",
                  when: [.signal(.retest), .flagSet(.escalated), .fact(.isLeaf), .fact(.notLanded), .fact(.nodeIdle)],
                  actor: .person, effects: [.discardAcceptanceTests, .resetAttempts]),
            .init(.questions, .acceptanceTests, "A person replaces an unlanded leaf's tests rather than answering",
                  when: [.signal(.retest), .flagSet(.needsInput), .fact(.isLeaf), .fact(.notLanded), .fact(.nodeIdle)],
                  actor: .person, effects: [.discardAcceptanceTests, .resetAttempts]),
            .init(.resumeWork, .breakdownGate, "Replan a ready root before any building in its subtree",
                  when: [.signal(.replan), .fact(.isRoot), .fact(.noBuildingInSubtree),
                         .fact(.nodeIdle), .fact(.ticketReady)],
                  actor: .person, effects: [.clearGates, .resetAttempts]),
        ])
    }
}
