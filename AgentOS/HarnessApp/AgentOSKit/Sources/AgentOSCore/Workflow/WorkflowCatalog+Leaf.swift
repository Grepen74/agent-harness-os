extension WorkflowCatalog {
    static var leafWorkflow: WorkflowDefinition {
        WorkflowDefinition(kind: .leaf, entryStage: .acceptanceTests, stages: [
            .init(id: .acceptanceTests, title: "Write acceptance tests", actor: .agent(.testAuthor),
                  phases: [.specified], limits: [.maxAttempts, .maxAgentRuns]),
            .init(id: .compileCheck, title: "Compile acceptance tests", actor: .harness, phases: [.specified]),
            .init(id: .acceptanceTestReview, title: "Review acceptance tests", actor: .reviewer,
                  phases: [.specified], limits: reviewLimits),
            .init(id: .questions, title: "Answer questions or approve assumptions", actor: .person,
                  phases: [.specified, .ready], flags: [.needsInput]),
            .init(id: .buildGate, title: "Approve build", actor: .person, phases: [.ready], gate: .build),
            .init(id: .implementation, title: "Implement the change", actor: .agent(.implementer),
                  phases: [.building], limits: [.maxAttempts, .maxAgentRuns]),
            .init(id: .ownChecks, title: "Check the leaf's own tests", actor: .agent(.verifier),
                  phases: [.checking], limits: [.maxAttempts]),
            .init(id: .brokenTestReport, title: "Return a broken acceptance test to its author", actor: .harness),
            .init(id: .landingQueue, title: "Wait in the landing queue", actor: .harness,
                  phases: [.landing], flags: [.blocked]),
            .init(id: .singleLandingChecks, title: "Full checks on the latest requirement branch",
                  actor: .agent(.verifier), phases: [.landing], limits: [.maxAttempts]),
            .init(id: .singleChangeReview, title: "Review the checked change", actor: .reviewer,
                  phases: [.landing], limits: reviewLimits),
            .init(id: .batchMemberReview, title: "Review each batch member", actor: .reviewer,
                  phases: [.landing], scope: .eachBatchMember, limits: reviewLimits),
            .init(id: .batchChecks, title: "Full checks of the combined batch", actor: .agent(.verifier),
                  phases: [.landing], scope: .combinedBatch, limits: [.maxAttempts]),
            .init(id: .batchSplit, title: "Split the failing batch", actor: .harness,
                  phases: [.landing], scope: .combinedBatch),
            .init(id: .landingRework, title: "Rework a landing conflict", actor: .agent(.implementer),
                  phases: [.ready, .building], limits: [.maxReworks, .maxAgentRuns]),
            .init(id: .proven, title: "Proven", actor: .harness, phases: [.proven]),
        ], transitions: authoringTransitions + landingTransitions)
    }

    static var reviewLimits: Set<WorkflowLimit> {
        [.reviewMaxRounds, .convergingReviewMaxRounds(multiplier: 2)]
    }

    private static var authoringTransitions: [WorkflowTransition] {
        [
            .init(.acceptanceTests, .acceptanceTests, "Continue the failed test author's kept draft",
                  when: [.fact(.testAuthorFailed), .fact(.attemptBudgetAvailable)], effects: [.keepTestDraft]),
            .init(.acceptanceTests, .compileCheck, "Acceptance tests have been written",
                  when: [.fact(.testsWritten)]),
            .init(.compileCheck, .acceptanceTests, "Compile diagnostics return directly to the test author",
                  when: [.fact(.compileFailed)]),
            .init(.compileCheck, .acceptanceTestReview, "Tests compile and review applies",
                  when: [.fact(.testsCompile), .fact(.reviewRequired)]),
            .init(.compileCheck, .questions, "No review applies, but input is required",
                  when: [.fact(.testsCompile), .fact(.inputRequired)], unless: [.fact(.reviewRequired)]),
            .init(.compileCheck, .buildGate, "Tests compile; neither review nor input is required",
                  when: [.fact(.testsCompile)], unless: [.fact(.reviewRequired), .fact(.inputRequired)]),
            .init(.acceptanceTests, .questions, "The test author needs answers before it can continue",
                  when: [.fact(.inputRequired)]),
            .init(.acceptanceTestReview, .questions, "Review passed; questions or assumptions need a person",
                  when: [.fact(.reviewPassed), .fact(.inputRequired)]),
            .init(.acceptanceTestReview, .buildGate, "Review passed with no outstanding input",
                  when: [.fact(.reviewPassed)], unless: [.fact(.inputRequired)]),
            .init(.acceptanceTestReview, .acceptanceTests, "Return review findings to the test author",
                  when: [.fact(.reviewFailed), .fact(.attemptBudgetAvailable)],
                  unless: [.fact(.escalationRequired)]),
            .init(.questions, .acceptanceTests, "Answers require the acceptance tests to be written again",
                  when: [.fact(.inputResolved)], unless: [.fact(.testsWritten)]),
            .init(.questions, .buildGate, "Required answers or approval have been supplied",
                  when: [.fact(.inputResolved)]),
            .init(.buildGate, .implementation, "A person approves the build",
                  when: [.signal(.build)], actor: .person),
            .init(.buildGate, .implementation, "A person approves autonomous build and checks",
                  when: [.signal(.go)], actor: .person),
            .init(.buildGate, .implementation, "The build gate is already open",
                  when: [.gateOpen(.build)]),
            .init(.implementation, .ownChecks, "The implementation is submitted for independent checks",
                  when: [.fact(.implementationSubmitted)]),
            .init(.implementation, .brokenTestReport, "The implementer reports an impossible acceptance test",
                  when: [.fact(.brokenTestReported)]),
            .init(.brokenTestReport, .acceptanceTests, "The report can safely return to the test author",
                  when: [.fact(.brokenTestReturnAllowed)]),
            .init(.ownChecks, .implementation, "Fix the failed own checks within the attempt budget",
                  when: [.fact(.checksFailed), .fact(.attemptBudgetAvailable)]),
            .init(.ownChecks, .landingQueue, "The leaf's own checks passed",
                  when: [.fact(.ownChecksPassed)]),
        ]
    }

    private static var landingTransitions: [WorkflowTransition] {
        [
            .init(.landingQueue, .singleLandingChecks, "Select a single candidate for full checks",
                  when: [.fact(.singleLanding)]),
            .init(.singleLandingChecks, .singleChangeReview, "Full checks passed; review the change",
                  when: [.fact(.landingChecksPassed), .fact(.reviewRequired)]),
            .init(.singleLandingChecks, .proven, "Checks passed and the unreviewed candidate landed",
                  when: [.fact(.landingChecksPassed), .fact(.landed)], unless: [.fact(.reviewRequired)]),
            .init(.singleLandingChecks, .implementation, "Fix a failed landing check",
                  when: [.fact(.checksFailed), .fact(.attemptBudgetAvailable)]),
            .init(.singleChangeReview, .proven, "The reviewed change landed",
                  when: [.fact(.reviewPassed), .fact(.landed)]),
            .init(.singleChangeReview, .singleChangeReview, "Wait for a person's approval of this reviewed candidate",
                  when: [.fact(.reviewPassed), .fact(.humanReviewRequired)],
                  unless: [.fact(.humanReviewApproved)]),
            .init(.singleChangeReview, .landingQueue, "A person approves this candidate for landing",
                  when: [.signal(.build), .fact(.reviewPassed), .fact(.humanReviewRequired)], actor: .person),
            .init(.singleChangeReview, .implementation, "Return change review findings to the implementer",
                  when: [.fact(.reviewFailed), .fact(.attemptBudgetAvailable)],
                  unless: [.fact(.escalationRequired), .fact(.brokenTestReported)]),
            .init(.singleChangeReview, .brokenTestReport, "Change review found broken acceptance tests",
                  when: [.fact(.brokenTestReported)]),
            .init(.landingQueue, .batchMemberReview, "Review each member before combined checks",
                  when: [.fact(.batchLanding), .fact(.reviewRequired)]),
            .init(.landingQueue, .batchChecks, "No member review applies; check the combined batch",
                  when: [.fact(.batchLanding)], unless: [.fact(.reviewRequired)]),
            .init(.batchMemberReview, .batchChecks, "Every member's review passed",
                  when: [.fact(.allMemberReviewsPassed)]),
            .init(.batchMemberReview, .implementation, "Return a member's change review findings",
                  when: [.fact(.reviewFailed), .fact(.attemptBudgetAvailable)],
                  unless: [.fact(.escalationRequired), .fact(.brokenTestReported)]),
            .init(.batchMemberReview, .brokenTestReport, "A member review found broken acceptance tests",
                  when: [.fact(.brokenTestReported)]),
            .init(.batchChecks, .batchSplit, "Split a failing batch to attribute the failure",
                  when: [.fact(.batchChecksFailed), .fact(.batchFailureAttributable)], effects: [.splitBatch]),
            .init(.batchSplit, .batchChecks, "Check a smaller batch",
                  when: [.fact(.smallerBatchReady)]),
            .init(.batchChecks, .proven, "Combined checks passed and the batch landed",
                  when: [.fact(.landingChecksPassed), .fact(.landed)]),
            .init(.singleLandingChecks, .landingRework, "Rebase conflicted before single landing",
                  when: [.fact(.landingConflicted)]),
            .init(.batchMemberReview, .landingRework, "A member conflicted while preparing the batch",
                  when: [.fact(.landingConflicted)]),
            .init(.batchChecks, .landingRework, "The batch candidate conflicted",
                  when: [.fact(.landingConflicted)]),
            .init(.landingRework, .ownChecks, "Check the reworked implementation before queueing again",
                  when: [.fact(.implementationSubmitted)]),
        ]
    }
}
