import AgentOSAdapters
import AgentOSCore
import Foundation

/// The product's code: one git monorepo, plus one working copy (git worktree) per leaf (doc 08).
///
///     workspace/
///       repo/                    the monorepo, `main` checked out. Only the landing queue writes here.
///         Sources/<Component>/   one Swift module per component
///         Tests/<Node>Tests/     each node's own acceptance tests
///       worktrees/<node>/        a leaf's branch `node/<id>`, where its agents work in isolation
///       artifacts/               check logs (evidence files)
///
/// `Package.swift` is generated from the folders and never committed, so it can never cause a merge
/// conflict (doc 08 §8: generate the conflict magnets).
///
/// Production: real repos in GitHub/GitLab/Gerrit, agents in sandboxes, a real merge queue.
public struct SimulationWorkspace: Workspace {
    public let root: URL

    public init(root: URL) { self.root = root }

    public var repoDirectory: URL { root.appending(path: "repo") }
    public var worktreesDirectory: URL { root.appending(path: "worktrees") }
    public var artifactsDirectory: URL { root.appending(path: "artifacts") }

    public func worktree(for id: NodeID) -> URL { worktreesDirectory.appending(path: id) }
    public func branch(for id: NodeID) -> String { "node/\(id)" }

    /// Creates the monorepo with an empty first commit on `main`, once.
    public func prepare() async throws {
        guard !FileManager.default.fileExists(atPath: repoDirectory.appending(path: ".git").path) else { return }
        try FileManager.default.createDirectory(at: repoDirectory, withIntermediateDirectories: true)
        try await git(["init", "-q", "-b", "main"], in: repoDirectory)
        try "Package.swift\n.build/\n.swiftpm/\nPackage.resolved\n"
            .write(to: repoDirectory.appending(path: ".gitignore"), atomically: true, encoding: .utf8)
        try "# Product monorepo (generated by the AgentOS simulator)\n"
            .write(to: repoDirectory.appending(path: "README.md"), atomically: true, encoding: .utf8)
        try await commitAll(in: repoDirectory, message: "Initial commit", author: "harness")
    }

    // MARK: Branch per leaf

    /// A fresh branch from the latest `main`, checked out in the leaf's own working copy.
    public func createWorktree(for id: NodeID) async throws -> URL {
        let directory = worktree(for: id)
        try? await removeWorktree(for: id)
        try FileManager.default.createDirectory(at: worktreesDirectory, withIntermediateDirectories: true)
        try await git(["worktree", "add", "-q", "-B", branch(for: id), directory.path, "main"], in: repoDirectory)
        return directory
    }

    public func removeWorktree(for id: NodeID) async throws {
        try await git(["worktree", "remove", "--force", worktree(for: id).path], in: repoDirectory)
        try await git(["worktree", "prune"], in: repoDirectory)
    }

    /// Commits everything in the working copy as the given run. Returns the new commit, or nil if nothing changed.
    @discardableResult
    public func commitAll(in directory: URL, message: String, author: String) async throws -> String? {
        try await git(["add", "-A"], in: directory)
        guard try await !git(["status", "--porcelain"], in: directory).isEmpty else { return nil }
        try await git(["-c", "user.name=\(author)", "-c", "user.email=\(author)@agents.agentos.local",
                       "commit", "-q", "-m", message], in: directory)
        return try await head(of: directory)
    }

    /// `main`'s history, newest first: "<sha> <author>: <message>".
    public func mainLog() async throws -> [String] {
        try await git(["log", "--format=%h %an: %s", "main"], in: repoDirectory)
            .split(separator: "\n").map(String.init)
    }

    public func head(of directory: URL) async throws -> String {
        try await git(["rev-parse", "HEAD"], in: directory).trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Files under Tests/ that this branch changed since it left `main`.
    public func changedTestFiles(in directory: URL) async throws -> [String] {
        try await git(["diff", "--name-only", "main...HEAD", "--", "Tests/"], in: directory)
            .split(separator: "\n").map(String.init)
    }

    // MARK: Landing

    /// Replays the branch on top of the latest `main`. On conflict, everything is put back as it was.
    public func rebaseOntoMain(_ directory: URL) async throws -> RebaseResult {
        let result = try await ProcessRunner.run("/usr/bin/env", ["git", "rebase", "-q", "main"], in: directory)
        guard result.status != 0 else { return .clean }
        let files = (try? await git(["diff", "--name-only", "--diff-filter=U"], in: directory))?
            .split(separator: "\n").map(String.init) ?? []
        try await abortRebase(directory)
        return .conflict(files: files)
    }

    public func abortRebase(_ directory: URL) async throws {
        _ = try await ProcessRunner.run("/usr/bin/env", ["git", "rebase", "--abort"], in: directory)
    }

    /// Rework: keep only the branch's first commit (the acceptance tests), drop the implementation, and
    /// move it on top of the latest `main`. The tests touch only the node's own folder, so this can't conflict.
    public func resetForRework(_ directory: URL) async throws {
        let commits = try await git(["rev-list", "--reverse", "main..HEAD"], in: directory).split(separator: "\n")
        guard let testsCommit = commits.first else { return }
        try await git(["reset", "-q", "--hard", String(testsCommit)], in: directory)
        try await git(["rebase", "-q", "main"], in: directory)
    }

    /// Fast-forwards `main` to the leaf's (already rebased and checked) branch. Returns the new `main`.
    public func landOnMain(_ id: NodeID) async throws -> String {
        try await git(["merge", "-q", "--ff-only", branch(for: id)], in: repoDirectory)
        return try await head(of: repoDirectory)
    }

    // MARK: Swift package

    /// Components that exist on `main` (for the decomposer's catalog).
    public func existingComponents() -> [String] { subfolders(of: repoDirectory.appending(path: "Sources")) }

    /// Writes `Package.swift` from the folders: every Sources/ folder is a library, every Tests/ folder a
    /// test target that may use all of them.
    public func prepareBuild(in directory: URL) async throws {
        let components = subfolders(of: directory.appending(path: "Sources"))
        let testTargets = subfolders(of: directory.appending(path: "Tests"))
        let all = components.map { "\"\($0)\"" }.joined(separator: ", ")
        let targets = components.map { "        .target(name: \"\($0)\")," }
            + testTargets.map { "        .testTarget(name: \"\($0)\", dependencies: [\(all)])," }
        try """
        // swift-tools-version: 6.0
        // GENERATED by the harness from the folder structure. Not committed; don't edit.
        import PackageDescription

        let package = Package(
            name: "Product",
            platforms: [.macOS(.v15)],
            targets: [
        \(targets.joined(separator: "\n"))
            ]
        )

        """.write(to: directory.appending(path: "Package.swift"), atomically: true, encoding: .utf8)
    }

    private func subfolders(of directory: URL) -> [String] {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: directory.path)) ?? []
        return names.filter { name in
            let files = (try? FileManager.default.contentsOfDirectory(atPath: directory.appending(path: name).path)) ?? []
            return files.contains { $0.hasSuffix(".swift") }
        }.sorted()
    }

    @discardableResult
    private func git(_ arguments: [String], in directory: URL) async throws -> String {
        let result = try await ProcessRunner.run("/usr/bin/env", ["git"] + arguments, in: directory, timeout: .seconds(60))
        guard result.status == 0 else {
            throw AgentFailure("git \(arguments.first ?? "") failed: \(result.output.suffix(300))")
        }
        return result.output
    }
}

/// Escapes text for use inside a Swift string literal.
func swiftLiteral(_ text: String) -> String {
    "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
}
