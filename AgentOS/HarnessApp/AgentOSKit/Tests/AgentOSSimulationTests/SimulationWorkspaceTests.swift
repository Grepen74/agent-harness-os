import AgentOSSimulation
import Foundation
import Testing

struct SimulationWorkspaceTests {
    @Test
    func discardingOutsideATestFolderKeepsOnlyThatFolderAndIgnoredFiles() async throws {
        let workspace = SimulationWorkspace(root: FileManager.default.temporaryDirectory
            .appending(path: "agentos-simulation-\(UUID().uuidString)"))
        defer { try? FileManager.default.removeItem(at: workspace.root) }
        try await workspace.prepare()
        let directory = try await workspace.createWorktree(for: "wn-1")
        func write(_ path: String, _ contents: String = "x\n") throws {
            let file = directory.appending(path: path)
            try FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
            try contents.write(to: file, atomically: true, encoding: .utf8)
        }
        try write("Tests/WN1Tests/WN1Tests.swift")
        try write("Sources/Greeting/Placeholder.swift")
        try write("README.md", "placeholder\n")
        try write("Package.swift")

        try await workspace.discardChanges(keeping: ["Tests/WN1Tests/"], in: directory)

        func exists(_ path: String) -> Bool { FileManager.default.fileExists(atPath: directory.appending(path: path).path) }
        #expect(exists("Tests/WN1Tests/WN1Tests.swift"))
        #expect(!exists("Sources/Greeting/Placeholder.swift"))
        #expect(exists("Package.swift"), "ignored files stay")
        #expect(try String(contentsOf: directory.appending(path: "README.md"), encoding: .utf8)
            == "# Product monorepo (generated by the AgentOS simulator)\n")
    }
}
